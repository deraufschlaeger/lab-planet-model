def find_radius_profile(density, mass_profile):
  ''' INPUT:
      density = constant value or array of values
      mass_profile = [m1,m2,m3,..., mN]

      OUTPUT looks like
      r_profile = [[r1lower, r1, r1upper], [r2lower, r2, r2upper], [r3lower, r3, r3upper], ... ,[rN-1lower, rN-1, rN-1upper], [rNlower, rN, rNupper]]
      '''


  N = len(mass_profile)
  r_profile = np.zeros((N,3))
  if type(density) not in [np.ndarray, list]:
    density = np.full(N, density)

  rilower = 0

  deltar = []

  for i in range(1,N): #stops @ N-1 (index of shell N is N-1)
    ''' r1lowr == 0 und rilower == ri-1upper (rNupper == Radius_gesamt(?))
    START AT SHELL NUMBER 2 (index 1)
    STEP 1: Calculate rilower
    STEP 2: set ri-1upper == rilower
    STEP 3: calculate ri-1

    STEP 4: FORMULA (15) CHECK
    '''

    if i == 1:
      r_profile[1][0] = (3*mass_profile[i]/(4*np.pi*density[i]))**(1/3) #deltar1 FORMULA (21) #STEP 1
      r_profile[0][2] = r_profile[1][0] #STEP 2
      r_profile[0][1] = r_profile[0][2]/2 #STEP 3

      rilower += mass_profile[0]/(4*np.pi*density[0]*r_profile[0][1]**2) #FORMULA (22)

      deltar.append(mass_profile[0]/(4*np.pi*density[0]*r_profile[0][1]**2))


